"""
Session 13 (owner, 2026-10-08): configuration C-raw, the contract without any reshaped data. Its semantic view reads
the raw fact and dimension tables only, exposes stock on hand NON ADDITIVE BY the snapshot month and no coverage or
closing-stock metric, and routes both to the procedures; its agent has three tools (the view, STOCK_COVERAGE,
CLOSING_STOCK) and C's generated instructions with the closing-stock routing rule. Both files are generated by
compiler/gen_craw.py and must not drift.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "generated"
RAW = {"FCT_STOCK_SNAPSHOT", "FCT_FORECAST", "DIM_ITEM", "DIM_GEO", "DIM_BATCH", "DIM_WAREHOUSE", "DIM_CALENDAR"}
# Session 15: gen_craw.py reads the published dataset through gen_agent.py; the private repository does not hold
# it (git-ignored), so a clone of it, and its CI, skip the drift test with the reason.
DATASET = pytest.mark.skipif(not (ROOT / "data" / "output" / "manifest.json").exists(),
                             reason="the published dataset is not in data/output/")


def load(name: str) -> dict:
    return yaml.safe_load((GEN / name).read_text())


@DATASET
def test_c_raw_files_do_not_drift(tmp_path):
    r = subprocess.run([sys.executable, "compiler/gen_craw.py", "--out-dir", str(tmp_path)], cwd=ROOT,
                       capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, r.stdout + r.stderr
    for name in ("c_raw_sv.yaml", "agent_c_raw.yaml"):
        assert (tmp_path / name).read_bytes() == (GEN / name).read_bytes(), f"generated/{name} drifts"


def test_the_view_reads_the_raw_tables_only():
    sv = load("c_raw_sv.yaml")
    tables = {t["base_table"]["table"] for t in sv["tables"]}
    assert tables <= RAW and {"FCT_STOCK_SNAPSHOT", "FCT_FORECAST"} <= tables, tables
    assert all(t["base_table"]["database"] == "LINKML_METRICS" and t["base_table"]["schema"] == "RAW" for t in sv["tables"])
    text = (GEN / "c_raw_sv.yaml").read_text()
    for banned in ("GAPFILLED", "B2_", "SPINE", "fwd", "gap_filled"):
        assert banned not in text, banned


def test_stock_on_hand_non_additive_by_the_snapshot_month_and_no_coverage_or_closing_metric():
    sv = load("c_raw_sv.yaml")
    assert not sv.get("metrics") and not sv.get("verified_queries")
    stock = next(t for t in sv["tables"] if t["base_table"]["table"] == "FCT_STOCK_SNAPSHOT")
    assert stock["metrics"] and all(m["non_additive_dimensions"] == [{"table": stock["name"], "dimension": "snapshot_month",
                                                                      "sort_direction": "ascending", "null_order": "last"}]
                                    for m in stock["metrics"])
    names = [m["name"] for t in sv["tables"] for m in t.get("metrics", [])]
    assert not [n for n in names if "coverage" in n or "closing" in n], names


def test_descriptions_route_closing_stock_and_coverage_to_the_procedures():
    sv = load("c_raw_sv.yaml")
    assert "closing_stock tool" in sv["description"] and "stock_coverage tool" in sv["description"]
    stock = next(t for t in sv["tables"] if t["base_table"]["table"] == "FCT_STOCK_SNAPSHOT")
    assert all("closing_stock tool" in m["description"] for m in stock["metrics"])


def test_three_tools_on_the_raw_view_and_the_two_procedures():
    spec, c = load("agent_c_raw.yaml"), load("agent_c.yaml")
    names = [t["tool_spec"]["name"] for t in spec["tools"]]
    assert names == ["c_raw_semantic_view", "stock_coverage", "closing_stock"]
    res = spec["tool_resources"]
    assert res["c_raw_semantic_view"]["semantic_view"] == "LINKML_METRICS.RAW.LINKML_C_RAW_SV"
    assert res["stock_coverage"] == c["tool_resources"]["stock_coverage"]
    assert res["closing_stock"]["identifier"] == "LINKML_METRICS.RAW.CLOSING_STOCK"
    assert res["closing_stock"]["type"] == "procedure"
    assert spec["tools"][1] == c["tools"][1]                                 # STOCK_COVERAGE's tool, unchanged
    cs = spec["tools"][2]["tool_spec"]
    assert cs["type"] == "generic"
    assert set(cs["input_schema"]["properties"]) == {"periods", "grain", "filters", "basis", "totals"}
    assert cs["input_schema"]["required"] == ["periods", "grain", "filters"]
    assert all(v["type"] == "string" for v in cs["input_schema"]["properties"].values())
    for k in ("models", "orchestration"):
        assert spec[k] == c[k]
    assert spec["instructions"]["response"] == c["instructions"]["response"]


def sentences(text: str) -> list[str]:
    return [s for s in re.split(r"(?<=\.)\s+", " ".join(text.split())) if s]


def test_c_instructions_plus_the_closing_stock_routing_rule():
    spec, c = load("agent_c_raw.yaml"), load("agent_c.yaml")
    mine = " ".join(spec["instructions"]["orchestration"].split())
    routing_c = "Route questions on stock on hand, closing stock and demand forecast to b2_semantic_view."
    kept = [s.replace("b2_semantic_view", "c_raw_semantic_view") for s in sentences(c["instructions"]["orchestration"])
            if s != routing_c]
    assert routing_c in " ".join(c["instructions"]["orchestration"].split())
    missing = [s for s in kept if s not in mine]
    assert not missing, missing
    assert "b2_semantic_view" not in mine
    assert re.search(r"Route every closing stock question[^.]*to closing_stock\.", mine)
    assert "Route questions on stock on hand at one month and on demand forecast to c_raw_semantic_view." in mine


def test_no_internal_reference_or_em_dash():
    text = (GEN / "agent_c_raw.yaml").read_text()
    body = "\n".join(l for l in text.splitlines() if not l.startswith("#"))
    assert "decision" not in body and "DEFINITION.md" not in body and "traps" not in body
    assert "session" not in body.lower()
    for name in ("agent_c_raw.yaml", "c_raw_sv.yaml"):
        assert "\u2014" not in (GEN / name).read_text(), name


def test_dimension_descriptions_are_b2s():
    """The attribute descriptions are the contract's, as in B2's generated view (which agent C reads): C-raw differs
    from C by its tables and tools, not by what the view says about an attribute."""
    def dims(sv):
        return {d["name"]: d.get("description") for t in sv["tables"] for d in t.get("dimensions", [])}
    mine, b2 = dims(load("c_raw_sv.yaml")), dims(load("b2_native_sv.yaml"))
    shared = set(mine) & set(b2) - {"month_start", "snapshot_month"}
    assert len(shared) >= 12 and all(mine[k] == b2[k] for k in shared), [k for k in shared if mine[k] != b2[k]]


def test_value_grounding_equals_b2s():
    """Owner, session 13 step 3: equal grounding with C. Every dimension the C-raw view shares with B2's enriched view
    (the file deployed for B2 and read by C) carries the same is_enum and sample_values, in the same place."""
    enriched = yaml.safe_load((ROOT / "snowflake" / "phase4_others" / "b2" / "LINKML_B2_SV_enriched.yaml").read_text())
    keys = ("is_enum", "sample_values")

    def grounding(sv):
        return {d["name"]: {k: d[k] for k in keys if k in d} for t in sv["tables"] for d in t.get("dimensions", [])}
    mine, b2 = grounding(load("c_raw_sv.yaml")), grounding(enriched)
    shared = set(mine) & set(b2)
    assert len([k for k in shared if b2[k]]) >= 18
    assert {k: mine[k] for k in shared} == {k: b2[k] for k in shared}
    assert all(not mine[k] for k in set(mine) - shared)

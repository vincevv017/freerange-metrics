"""Agent C: create or drop the permanent agent LINKML_METRICS.RAW.LINKML_C from generated/agent_c.yaml.

    python snowflake/phase4_agent_c/deploy_agent.py create
    python snowflake/phase4_agent_c/deploy_agent.py drop
    python snowflake/phase4_agent_c/deploy_agent.py publish   # session 8a: the five-beat cycle on the existing agent
    python snowflake/phase4_agent_c/deploy_agent.py versions  # SHOW VERSIONS, each spec against the generated file

Run as perso, USE SECONDARY ROLES NONE, LINKML_METRICS_ROLE (the agent's owner, the role LINKML_SVC calls it with).
The spec is the generated file, without its comment header; nothing is edited by hand.
"""

import json
import sys
from pathlib import Path

import snowflake.connector
import yaml

ROOT = Path(__file__).resolve().parents[2]
AGENT = "LINKML_METRICS.RAW.LINKML_C"

con = snowflake.connector.connect(connection_name="perso")
cur = con.cursor()
cur.execute("USE SECONDARY ROLES NONE")
cur.execute("USE ROLE LINKML_METRICS_ROLE")
if sys.argv[1] == "create":
    spec = yaml.safe_dump(yaml.safe_load((ROOT / "generated" / "agent_c.yaml").read_text()), sort_keys=False,
                          allow_unicode=True, width=1000)
    cur.execute(f"CREATE AGENT {AGENT} COMMENT = 'Agent C, generated by compiler/gen_agent.py' "
                f"FROM SPECIFICATION $${spec}$$")
    print(cur.sfqid)
    print(cur.execute("SHOW AGENTS LIKE 'LINKML_C' IN SCHEMA LINKML_METRICS.RAW").fetchall()[0][:6])
    print(cur.execute(f"SHOW GRANTS ON AGENT {AGENT}").fetchall())
elif sys.argv[1] == "publish":
    # Beat 0: the spec parses and its instructions are single strings.
    spec_obj = yaml.safe_load((ROOT / "generated" / "agent_c.yaml").read_text())
    for k in ("orchestration", "response"):
        assert isinstance(spec_obj["instructions"][k], str)
    spec = yaml.safe_dump(spec_obj, sort_keys=False, allow_unicode=True, width=1000)
    assert yaml.safe_load(spec) == spec_obj
    cur.execute(f"ALTER AGENT {AGENT} MODIFY LIVE VERSION SET SPECIFICATION = $${spec}$$")
    print("modify live", cur.sfqid)
    cur.execute(f"ALTER AGENT {AGENT} COMMIT")
    print("commit", cur.sfqid)
    cur.execute(f"ALTER AGENT {AGENT} ADD LIVE VERSION FROM LAST")
    print("add live from last", cur.sfqid)
    rows = cur.execute(f"SHOW VERSIONS IN AGENT {AGENT}").fetchall()
    cols = [d[0] for d in cur.description]
    named = [dict(zip(cols, r)) for r in rows if dict(zip(cols, r))["name"]]
    last = max(named, key=lambda r: int(r["name"].split("$")[1]))["name"]     # read, not computed
    cur.execute(f"ALTER AGENT {AGENT} SET DEFAULT_VERSION = '{last}'")
    print("default", last, cur.sfqid)
if sys.argv[1] in ("publish", "versions"):
    want = yaml.safe_load((ROOT / "generated" / "agent_c.yaml").read_text())
    rows = cur.execute(f"SHOW VERSIONS IN AGENT {AGENT}").fetchall()
    cols = [d[0] for d in cur.description]
    for r in map(lambda x: dict(zip(cols, x)), rows):
        print(r["name"] or "LIVE", "default" if r["is_default"] == "true" else "", r["alias"],
              "spec equal to generated:", json.loads(r["agent_spec"]) == want)
    d = dict(zip([c[0] for c in cur.execute(f"DESCRIBE AGENT {AGENT}").description], cur.fetchone()))
    print("DESCRIBE spec equal to generated:", json.loads(d["agent_spec"]) == want)
elif sys.argv[1] == "drop":
    cur.execute(f"DROP AGENT IF EXISTS {AGENT}")
    print("dropped")
print(cur.execute("SELECT CURRENT_ROLE(), CURRENT_SECONDARY_ROLES()").fetchone())

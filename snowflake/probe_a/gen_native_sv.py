"""
Phase 0, probe A: generate the most honest native semantic view (config B) over the RAW tables.

    python snowflake/probe_a/gen_native_sv.py [--frame rows|range] > snowflake/probe_a/10_native_sv_<frame>.sql

What it declares, natively:
- stock as semi-additive over time (NON ADDITIVE BY the snapshot month), forecast as a flow;
- 24 forward cumulative forecast window metrics C1..C24 (k months AFTER the row's month);
- a nonzero-month counter window for the beyond-horizon average;
- one derived COVERAGE metric: the legacy cascade (25-branch CASE) over those metrics.
That is the legacy metric family, regenerated inside the semantic view. It is generated, not hand-written,
for the same reason the legacy metrics were: nobody types 24 windows and a 25-branch CASE twice the same way.

--frame rows : ROWS BETWEEN 1 FOLLOWING AND k FOLLOWING over month_start (counts result rows: T2 exposure)
--frame range: RANGE BETWEEN 1 FOLLOWING AND k FOLLOWING over a numeric month index (counts months)
"""

from __future__ import annotations

import argparse

H = 24


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--frame", choices=["rows", "range"], default="rows")
    p.add_argument("--with-coverage", action="store_true",
                   help="add the derived COVERAGE metric (rejected: 010273 Unsupported window metrics in derived metric)")
    args = p.parse_args()
    frame = args.frame
    name = f"LINKML_METRICS.RAW.COVERAGE_NATIVE_{frame.upper()}_SV"
    order = "cal.month_start" if frame == "rows" else "cal.month_index"
    unit = frame.upper()

    windows = []
    for k in range(1, H + 1):
        windows.append(
            f"    fc.c{k:02d} AS SUM(fc.forecast_qty) OVER (PARTITION BY EXCLUDING cal.month_start, cal.month_index "
            f"ORDER BY {order} {unit} BETWEEN 1 FOLLOWING AND {k} FOLLOWING)"
        )
    windows.append(
        f"    fc.nz{H} AS SUM(fc.forecast_nonzero_month) OVER (PARTITION BY EXCLUDING cal.month_start, cal.month_index "
        f"ORDER BY {order} {unit} BETWEEN 1 FOLLOWING AND {H} FOLLOWING)"
    )

    branches = ["      WHEN stock.stock_qty IS NULL OR stock.stock_qty = 0 THEN 0",
                "      WHEN stock.stock_qty <= fc.c01 THEN stock.stock_qty / fc.c01"]
    for n in range(2, H + 1):
        branches.append(f"      WHEN stock.stock_qty <= fc.c{n:02d} THEN {n - 1} + "
                        f"(stock.stock_qty - fc.c{n - 1:02d}) / (fc.c{n:02d} - fc.c{n - 1:02d})")
    branches.append(f"      WHEN fc.nz{H} > 0 THEN stock.stock_qty / (fc.c{H} / fc.nz{H})")
    branches.append("      ELSE NULL")

    coverage = ""
    if args.with_coverage:
        coverage = (",\n    coverage_months AS CASE\n" + "\n".join(branches) + "\n    END\n"
                    "      COMMENT = 'Forward stock coverage in months (H = 24).'")
    print(f"""-- GENERATED by snowflake/probe_a/gen_native_sv.py --frame {frame}{' --with-coverage' if args.with_coverage else ''}. Phase 0 probe A, config B. Do not edit.
USE SECONDARY ROLES NONE;
USE ROLE LINKML_METRICS_ROLE;

CREATE OR REPLACE SEMANTIC VIEW {name}
  TABLES (
    item  AS LINKML_METRICS.RAW.DIM_ITEM      PRIMARY KEY (item_id)
      COMMENT = 'Item master: SKU > family > range. Declared unique on item_id.',
    geo   AS LINKML_METRICS.RAW.DIM_GEO       PRIMARY KEY (country_id),
    cal   AS LINKML_METRICS.RAW.DIM_CALENDAR  PRIMARY KEY (month_start),
    batch AS LINKML_METRICS.RAW.DIM_BATCH     PRIMARY KEY (batch_id),
    wh    AS LINKML_METRICS.RAW.DIM_WAREHOUSE PRIMARY KEY (warehouse_id),
    stock AS LINKML_METRICS.RAW.FCT_STOCK_SNAPSHOT PRIMARY KEY (snapshot_month, batch_id, warehouse_id)
      COMMENT = 'Monthly closing stock per batch and warehouse.',
    fc    AS LINKML_METRICS.RAW.FCT_FORECAST  PRIMARY KEY (forecast_month, item_id, country_id)
      COMMENT = 'Monthly demand forecast per SKU and country. Carries no batch or warehouse.'
  )
  RELATIONSHIPS (
    stock_item  AS stock (item_id)        REFERENCES item,
    stock_geo   AS stock (country_id)     REFERENCES geo,
    stock_cal   AS stock (snapshot_month) REFERENCES cal,
    stock_batch AS stock (batch_id)       REFERENCES batch,
    stock_wh    AS stock (warehouse_id)   REFERENCES wh,
    fc_item     AS fc (item_id)           REFERENCES item,
    fc_geo      AS fc (country_id)        REFERENCES geo,
    fc_cal      AS fc (forecast_month)    REFERENCES cal
  )
  DIMENSIONS (
    item.sku_code       AS sku_code,
    item.family_code    AS family_code,
    item.range_code     AS range_code,
    item.item_type      AS item_type,
    geo.country_code    AS country_code,
    geo.region_code     AS region_code,
    cal.month_start     AS month_start  COMMENT = 'Analysis month for stock; forecast month for forecast.',
    cal.month_index     AS year * 12 + month_num,
    batch.batch_status  AS batch_status COMMENT = 'Stock-only attribute: the forecast has no batch.',
    wh.warehouse_code   AS warehouse_code,
    stock.expiry_bucket AS expiry_bucket,
    stock.snapshot_month AS snapshot_month
  )
  METRICS (
    stock.stock_qty NON ADDITIVE BY (stock.snapshot_month ASC NULLS LAST) AS SUM(stock_qty_eq)
      COMMENT = 'Closing stock in QTY_EQ: latest snapshot per period, never summed across months.',
    fc.forecast_qty AS SUM(forecast_qty_eq) COMMENT = 'Forecast in QTY_EQ, a flow.',
    fc.forecast_nonzero_month AS IFF(SUM(forecast_qty_eq) > 0, 1, 0),
{",\n".join(windows)}{coverage}
  )
  COMMENT = 'Phase 0 probe A (config B): native semantic view, {frame} frames.';
""")


if __name__ == "__main__":
    main()

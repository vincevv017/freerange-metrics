"""
Session 6, step 0: native closing stock, the baseline of step 1 of the article. Measures, fixes nothing.

    python snowflake/probe_closing/run_probe_closing.py (raw output pasted into results.md)

a. Every probe semantic view in LINKML_METRICS.RAW still compiles after the session 5 reloads (phase 2 open
   question 4): one SEMANTIC_VIEW() query per view, asserted on a number.
b. COVERAGE_SPINE_CLOSING_PROBE_SV, a copy of the best native build (COVERAGE_SPINE_SV, stock NON ADDITIVE BY
   stock.snapshot_month) with year, quarter and year_quarter dimensions added from DIM_CALENDAR, answers the three
   closing-stock heroes of data/traps.yaml for Q2 2026. Each value is compared with the expected value and with
   every wrong value traps.yaml lists, so a mismatch names the wrong behaviour it matches.

Connection "perso", USE SECONDARY ROLES NONE, LINKML_METRICS_ROLE. No agent, no LLM.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import snowflake.connector
import yaml

ROOT = Path(__file__).resolve().parents[2]
TRAPS = yaml.safe_load((ROOT / "data" / "traps.yaml").read_text())
CS = {c["id"]: c for c in TRAPS["closing_stock"]}
SRC = ROOT / "snowflake" / "probe_a" / "20_spine_sv.sql"
DDL = ROOT / "snowflake" / "probe_closing" / "10_spine_closing_PROBE.sql"
SV = "LINKML_METRICS.RAW.COVERAGE_SPINE_CLOSING_PROBE_SV"
QUARTER = "2026-Q2"


def closing_ddl() -> str:
    """The base spine view, renamed, with three calendar dimensions added. Nothing else changes."""
    src = SRC.read_text()
    src = src.replace("LINKML_METRICS.RAW.COVERAGE_SPINE_SV", SV)
    src = src.replace("-- GENERATED by snowflake/probe_a/gen_spine_sv.py. Phase 0 probe A, config B (second build). Do not edit.",
                      "-- GENERATED by snowflake/probe_closing/run_probe_closing.py from snowflake/probe_a/20_spine_sv.sql.\n"
                      "-- Session 6 step 0 probe: the same view plus year, quarter and year_quarter dimensions. Do not edit.")
    anchor = "    stock.snapshot_month AS snapshot_month\n"
    assert anchor in src
    src = src.replace(anchor, "    cal.year           AS year,\n"
                              "    cal.quarter        AS quarter,\n"
                              "    cal.year_quarter   AS year || '-Q' || quarter COMMENT = 'Calendar quarter, for example 2026-Q2.',\n"
                              + anchor)
    src = src.replace("COMMENT = 'Phase 0 probe A (config B, second build): forward spine as a query-defined logical table.'",
                      "COMMENT = 'Session 6 probe: COVERAGE_SPINE_SV plus quarter dimensions (closing stock baseline).'")
    return src


def statements(sql: str) -> list[str]:
    out, cur = [], []
    for line in sql.splitlines():
        if not cur and (not line.strip() or line.startswith("--")):
            continue
        cur.append(line)
        if line.rstrip().endswith(";"):
            out.append("\n".join(cur).rstrip().rstrip(";"))
            cur = []
    return out


def run(cur, sql):
    try:
        rows = cur.execute(sql).fetchall()
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r)) for r in rows], None, cur.sfqid
    except snowflake.connector.errors.ProgrammingError as e:
        return None, f"error {e.errno}: {e.msg.splitlines()[0]}", e.sfqid


def fmt(v):
    return "NULL" if v is None else f"{float(v):g}"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--connection", default="perso")
    a = p.parse_args()
    con = snowflake.connector.connect(connection_name=a.connection)
    cur = con.cursor()
    for s in ("USE SECONDARY ROLES NONE", "USE ROLE LINKML_METRICS_ROLE", "USE WAREHOUSE LINKML_METRICS_WH",
              "USE SCHEMA LINKML_METRICS.RAW"):
        cur.execute(s)
    session = cur.execute("SELECT CURRENT_ROLE(), CURRENT_SECONDARY_ROLES()").fetchone()
    print("# Probe closing stock: raw output\n")
    print(f"Session: `{session}`\n")

    # ---------------------------------------------------------------- a. probe views still compile
    print("## a. Probe semantic views in RAW after the session 5 reloads\n")
    print("| View | Query | Returned | Expected | Status | Query id |\n|---|---|---|---|---|---|")
    views = [r[1] for r in cur.execute("SHOW SEMANTIC VIEWS IN SCHEMA LINKML_METRICS.RAW").fetchall()]
    t1 = "item.family_code = 'PANTRY_FLOUR' AND geo.country_code = 'FR'"
    for v in sorted(views):
        fq = f"LINKML_METRICS.RAW.{v}"
        if v in ("COVERAGE_NATIVE_ROWS_SV", "COVERAGE_NATIVE_RANGE_SV"):
            sql = (f"SELECT * FROM SEMANTIC_VIEW({fq} DIMENSIONS item.family_code, geo.country_code "
                   f"METRICS stock.stock_qty WHERE {t1})")
            col, exp = "STOCK_QTY", 1400.0     # NON ADDITIVE BY: latest snapshot (AS_OF), H01 1200 + H02 200
        elif v == "COVERAGE_SPINE_ASOF_PROBE_SV":
            sql = (f"SELECT * FROM SEMANTIC_VIEW({fq} DIMENSIONS item.family_code, geo.country_code "
                   f"METRICS coverage_months WHERE {t1} VARIABLES analysis_month => DATE '2026-06-01')")
            col, exp = "COVERAGE_MONTHS", 2.8
        else:
            sql = (f"SELECT * FROM SEMANTIC_VIEW({fq} DIMENSIONS item.family_code, geo.country_code, cal.month_start "
                   f"METRICS coverage_months WHERE {t1} AND cal.month_start = '2026-06-01')")
            col, exp = "COVERAGE_MONTHS", 2.8
        rows, err, qid = run(cur, sql)
        got = err or ("; ".join(fmt(r[col]) for r in rows) if rows else "no row")
        ok = rows is not None and len(rows) == 1 and rows[0][col] is not None and abs(float(rows[0][col]) - exp) < 1e-4
        print(f"| `{v}` | `{sql}` | {got} | {exp:g} | {'COMPILES, value ok' if ok else ('FAILS' if err else 'COMPILES, value differs')} | `{qid}` |")

    # ---------------------------------------------------------------- b. closing stock through the native view
    ddl = closing_ddl()
    DDL.write_text(ddl)
    for s in statements(ddl):
        cur.execute(s)
    print(f"\n## b. Closing stock heroes, {QUARTER}, through `{SV}`\n")
    print("| Case | Query | Row | Returned | Expected | Matches | Query id |\n|---|---|---|---|---|---|---|")

    def wrongs(cid):
        return {k: v for k, v in CS[cid]["wrong"].items() if isinstance(v, (int, float))}

    def verdict(got, exp, wrong):
        if got is None:
            return "no row (member lost)"
        if abs(got - exp) < 1e-6:
            return "expected"
        hit = [k for k, v in wrong.items() if abs(got - v) < 1e-6]
        return ", ".join(hit) if hit else "none of the listed values"

    skus = "('SKU-H11', 'SKU-H12')"
    cases = [
        ("1. SKU x quarter", f"SELECT * FROM SEMANTIC_VIEW({SV} DIMENSIONS item.sku_code, cal.year_quarter METRICS stock.stock_qty "
                             f"WHERE item.sku_code IN {skus} AND geo.country_code = 'CH' AND cal.year_quarter = '{QUARTER}')",
         "SKU_CODE", {"SKU-H11": "CS_LAST_MONTH_GAP", "SKU-H12": "CS_MIDDLE_MONTH_GAP"}),
        ("2. family x quarter", f"SELECT * FROM SEMANTIC_VIEW({SV} DIMENSIONS item.family_code, cal.year_quarter METRICS stock.stock_qty "
                                f"WHERE item.family_code = 'SNACK_BARS' AND geo.country_code = 'CH' AND cal.year_quarter = '{QUARTER}')",
         "FAMILY_CODE", {"SNACK_BARS": "CS_FAMILY"}),
        ("3. family x country, quarter filter, no time dimension",
         f"SELECT * FROM SEMANTIC_VIEW({SV} DIMENSIONS item.family_code, geo.country_code METRICS stock.stock_qty "
         f"WHERE item.family_code = 'SNACK_BARS' AND geo.country_code = 'CH' AND cal.year_quarter = '{QUARTER}')",
         "FAMILY_CODE", {"SNACK_BARS": "CS_FAMILY"}),
        ("3b. SKU x country, quarter filter, no time dimension",
         f"SELECT * FROM SEMANTIC_VIEW({SV} DIMENSIONS item.sku_code, geo.country_code METRICS stock.stock_qty "
         f"WHERE item.sku_code IN {skus} AND geo.country_code = 'CH' AND cal.year_quarter = '{QUARTER}')",
         "SKU_CODE", {"SKU-H11": "CS_LAST_MONTH_GAP", "SKU-H12": "CS_MIDDLE_MONTH_GAP"}),
    ]
    for label, sql, key, expect in cases:
        rows, err, qid = run(cur, sql)
        if err:
            print(f"| {label} | `{sql}` | n/a | {err} | n/a | n/a | `{qid}` |")
            continue
        got = {r[key]: r["STOCK_QTY"] for r in rows}
        for member, cid in expect.items():
            g = None if got.get(member) is None else float(got[member])
            print(f"| {label} | `{sql}` | {member} | {fmt(g) if member in got else 'no row'} | {CS[cid]['expected']:g} "
                  f"| {verdict(g, CS[cid]['expected'], wrongs(cid)) if member in got else 'no row (member lost)'} | `{qid}` |")

    # 4. SKU x month: one row per month expected, June of SKU-H11 = 0 (expected) or absent
    sql = (f"SELECT * FROM SEMANTIC_VIEW({SV} DIMENSIONS item.sku_code, cal.month_start METRICS stock.stock_qty "
           f"WHERE item.sku_code IN {skus} AND geo.country_code = 'CH' AND cal.year_quarter = '{QUARTER}') "
           f"ORDER BY sku_code, month_start")
    rows, err, qid = run(cur, sql)
    expected = {("SKU-H11", "2026-04-01"): 400, ("SKU-H11", "2026-05-01"): 350, ("SKU-H11", "2026-06-01"): 0,
                ("SKU-H12", "2026-04-01"): 500, ("SKU-H12", "2026-05-01"): 0, ("SKU-H12", "2026-06-01"): 450}
    got = {} if err else {(r["SKU_CODE"], str(r["MONTH_START"])): r["STOCK_QTY"] for r in rows}
    for (sku, m), e in expected.items():
        g = got.get((sku, m))
        res = "expected" if g is not None and abs(float(g) - e) < 1e-6 else ("no row" if (sku, m) not in got else "differs")
        print(f"| 4. SKU x month | `{sql}` | {sku} {m} | {err or ('no row' if (sku, m) not in got else fmt(g))} | {e} | {res} | `{qid}` |")
    con.close()


if __name__ == "__main__":
    main()

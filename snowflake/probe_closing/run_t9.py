"""
Session 7, step 0, trap T9 (stale stock in coverage) on native views. Measures, fixes nothing in the probe views.

    python snowflake/probe_closing/run_t9.py (raw output pasted into results.md)

SKU-H11 x CH: stock 400 in April, 350 in May, no snapshot in June (AS_OF), forecast 100 a month. Expected coverage at
AS_OF: 0 (NO_STOCK). Wrong: 3.5, the last known stock (350) over the forecast. Each view is asked three ways: a month
filter equal to AS_OF, a filter on the quarter that ends at AS_OF (as a month range, and as the quarter dimension
where the view has one), and no month at all.

Views:
- COVERAGE_SPINE_SV: probe A's best native coverage build (B2 spine), stock NON ADDITIVE BY the snapshot month.
- COVERAGE_SPINE_CLOSING_PROBE_SV: the same plus quarter dimensions (session 6).
- COVERAGE_NATIVE_RANGE_SV: probe A's first build (B1), stock NON ADDITIVE BY; it carries no coverage metric (a
  derived metric cannot reference window metrics, 010273), so only the stock it picks is read.
- COVERAGE_SPINE_GAPFILLED_PROBE_SV (created here): COVERAGE_SPINE_CLOSING_PROBE_SV with its stock table replaced by
  the generated gap-filled snapshot view. Nothing else changes.

Connection "perso", USE SECONDARY ROLES NONE, LINKML_METRICS_ROLE. No agent, no LLM.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "snowflake" / "phase3_procedure"))
sys.path.insert(0, str(ROOT / "snowflake" / "probe_closing"))
from deploy import connect  # noqa: E402
from run_probe_closing import fmt, run, statements  # noqa: E402

T9 = next(t for t in yaml.safe_load((ROOT / "data" / "traps.yaml").read_text())["traps"] if t["id"] == "T9")
EXPECTED, WRONG = T9["expected"], T9["wrong"]["last_known_stock_over_forecast"]
SRC = ROOT / "snowflake" / "probe_closing" / "10_spine_closing_PROBE.sql"
DDL = ROOT / "snowflake" / "probe_closing" / "20_spine_gapfilled_PROBE.sql"
GAPFILLED_SV = "LINKML_METRICS.RAW.COVERAGE_SPINE_GAPFILLED_PROBE_SV"
TOL = 1e-6


def gapfilled_ddl() -> str:
    src = SRC.read_text()
    old_t = "    stock AS LINKML_METRICS.RAW.FCT_STOCK_SNAPSHOT PRIMARY KEY (snapshot_month, batch_id, warehouse_id),"
    assert old_t in src
    src = src.replace(old_t, "    stock AS LINKML_METRICS.RAW.FCT_STOCK_SNAPSHOT_GAPFILLED PRIMARY KEY (snapshot_month, batch_id, warehouse_id),")
    src = src.replace("LINKML_METRICS.RAW.COVERAGE_SPINE_CLOSING_PROBE_SV", GAPFILLED_SV)
    src = src.replace("-- GENERATED by snowflake/probe_closing/run_probe_closing.py from snowflake/probe_a/20_spine_sv.sql.\n"
                      "-- Session 6 step 0 probe: the same view plus year, quarter and year_quarter dimensions. Do not edit.",
                      "-- GENERATED by snowflake/probe_closing/run_t9.py from 10_spine_closing_PROBE.sql. Do not edit.\n"
                      "-- Session 7 T9 probe: the same view, stock read from the generated gap-filled snapshot view.")
    src = src.replace("COMMENT = 'Session 6 probe: COVERAGE_SPINE_SV plus quarter dimensions (closing stock baseline).'",
                      "COMMENT = 'Session 7 probe: COVERAGE_SPINE_CLOSING_PROBE_SV over the gap-filled snapshot (T9).'")
    return src


def verdict(v) -> str:
    if v is None:
        return "NULL"
    if abs(v - EXPECTED) < TOL:
        return "expected (0)"
    if abs(v - WRONG) < TOL:
        return "**wrong: last known stock over forecast**"
    return "**wrong, other value**"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--connection", default="perso")
    a = p.parse_args()
    con = connect(a.connection)
    cur = con.cursor()
    cur.execute("ALTER SESSION SET USE_CACHED_RESULT = FALSE")
    ddl = gapfilled_ddl()
    DDL.write_text(ddl)
    for s in statements(ddl):
        cur.execute(s)

    member = "item.sku_code = 'SKU-H11' AND geo.country_code = 'CH'"
    month = "cal.month_start = '2026-06-01'"
    rng = "cal.month_start BETWEEN '2026-04-01' AND '2026-06-01'"
    qtr = "cal.year_quarter = '2026-Q2'"
    spine = [("COVERAGE_SPINE_SV (B2)", "LINKML_METRICS.RAW.COVERAGE_SPINE_SV", False),
             ("COVERAGE_SPINE_CLOSING_PROBE_SV (B2 + quarter)", "LINKML_METRICS.RAW.COVERAGE_SPINE_CLOSING_PROBE_SV", True),
             ("COVERAGE_SPINE_GAPFILLED_PROBE_SV (B2 + quarter, gap-filled stock)", GAPFILLED_SV, True)]
    print("# T9 on native views: raw output\n")
    print(f"Expected coverage {EXPECTED:g} (NO_STOCK); wrong value {WRONG:g} (350 over 100 a month).\n")
    print("| View | Time filter | Coverage | Stock picked | Forecast c24 | Verdict | Query id |\n|---|---|---|---|---|---|---|")
    for label, sv, has_q in spine:
        filters = [("month = AS_OF", month), ("month range April to June", rng)]
        if has_q:
            filters.append(("quarter dimension = 2026-Q2", qtr))
        filters.append(("no month", None))
        for fl, cond in filters:
            where = member + (f" AND {cond}" if cond else "")
            sql = (f"SELECT * FROM SEMANTIC_VIEW({sv} DIMENSIONS item.sku_code, geo.country_code "
                   f"METRICS coverage_months, stock.stock_qty, fwd.c24 WHERE {where})")
            rows, err, qid = run(cur, sql)
            if err:
                print(f"| {label} | {fl} | {err} | n/a | n/a | error | `{qid}` |")
                continue
            if not rows:
                print(f"| {label} | {fl} | no row | n/a | n/a | member lost | `{qid}` |")
                continue
            r = rows[0]
            cov = None if r["COVERAGE_MONTHS"] is None else float(r["COVERAGE_MONTHS"])
            print(f"| {label} | {fl} | {fmt(cov)} | {fmt(r['STOCK_QTY'])} | {fmt(r['C24'])} | {verdict(cov)} | `{qid}` |")
    b1 = "LINKML_METRICS.RAW.COVERAGE_NATIVE_RANGE_SV"
    for fl, cond in (("month = AS_OF", month), ("month range April to June", rng), ("no month", None)):
        where = member + (f" AND {cond}" if cond else "")
        sql = f"SELECT * FROM SEMANTIC_VIEW({b1} DIMENSIONS item.sku_code, geo.country_code METRICS stock.stock_qty WHERE {where})"
        rows, err, qid = run(cur, sql)
        stock = err or ("no row" if not rows else fmt(rows[0]["STOCK_QTY"]))
        picked = "" if err or not rows else (" (May carried)" if rows[0]["STOCK_QTY"] and abs(float(rows[0]["STOCK_QTY"]) - 350) < TOL else "")
        print(f"| COVERAGE_NATIVE_RANGE_SV (B1) | {fl} | n/a (no coverage metric, 010273) | {stock}{picked} | n/a | "
              f"{'stock 350 would give the wrong value' if picked else 'no stale stock'} | `{qid}` |")
    con.close()


if __name__ == "__main__":
    main()
